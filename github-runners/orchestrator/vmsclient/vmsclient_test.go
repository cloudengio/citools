// tartImage returns the configuration of a tart pool that clones image. The
// runner directory is set because it is required, see TartConfig.Validate,
// which building a backend from a pool configuration runs first.
func tartImage(image string) TartConfig {
	return TartConfig{
		Source:    ociimage.Source{Image: image},
		RunnerDir: "/Users/admin/actions-runner",
	}
}

func tartPool(image string) PoolConfig {
	cfg := tartImage(image)
	return PoolConfig{Tart: &cfg}
}

// tartBackendFor builds the backend for a tart pool, which fails only for a
// configuration whose image is not a reference; a test that wants that failure
// calls newTartBackend itself.
func tartBackendFor(t *testing.T, pool string, cfg TartConfig) *tartBackend {
	t.Helper()
	p, err := newTartBackend(pool, cfg, slog.Default())
	if err != nil {
		t.Fatalf("newTartBackend: %v", err)
	}
	return p
}

func TestVMNamePrefix(t *testing.T) {
	// The prefix must match the names generated by tartBackend.New.
	p := tartBackendFor(t, "macos", tartImage("macos-ci"))
	inst, err := p.New(context.Background())
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	name := inst.ID()
	if got, want := name[:len(vmNamePrefix("macos", "macos-ci"))], vmNamePrefix("macos", "macos-ci"); got != want {
		t.Errorf("%v: got %v, want %v", name, got, want)
	}
}

func TestProviderSelection(t *testing.T) {
	// A tart-configured pool yields a tart provider.
	p, err := tartPool("macos-ci").newBackend(context.Background(), "macos")
	if err != nil {
		t.Fatal(err)
	}
	if p.Name() != TartKind || p.Details().Image().String() != "macos-ci" {
		t.Errorf("unexpected provider: name=%q image=%q", p.Name(), p.Details().Image())
	}
	// The name is known before the provider is built, and is the name the
	// provider goes on to report, see basepool.ProviderNew.
	if got, want := tartImage("macos-ci").Backend("macos").Name(), p.Name(); got != want {
		t.Errorf("the configuration promises %v and the provider reports %v", got, want)
	}
	// A pool with no backend configured is rejected.
	if _, err := (PoolConfig{}).newBackend(context.Background(), "empty"); !errors.Is(err, ErrNoBackend) {
		t.Errorf("empty pool: got %v, want ErrNoBackend", err)
	}
}

// TestVMNamePrefixRemoteImage verifies that a VM created from a remote image
// is named after the image alone, since "/" and ":" cannot appear in a VM name.
// Which part of a reference the name is taken from is ociimage's own business,
// and is tested there.
func TestVMNamePrefixRemoteImage(t *testing.T) {
	p := tartBackendFor(t, "linux", tartImage("mm-1:5001/linux-ci:latest"))
	inst, err := p.New(context.Background())
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	name := inst.ID()
	if want := vmNamePrefix("linux", "linux-ci"); !strings.HasPrefix(name, want) {
		t.Errorf("VM name %q does not start with %q", name, want)
	}
	if strings.ContainsAny(name, "/:") {
		t.Errorf("VM name %q contains a character not valid in a VM name", name)
	}
	// The provider still reports the configured image, which tart needs in full
	// to clone from the registry, and reports it parsed so that a caller can
	// take it apart without parsing it again.
	if got, want := p.Details().Image().String(), "mm-1:5001/linux-ci:latest"; got != want {
		t.Errorf("Details().Image(): got %q, want %q", got, want)
	}
	if got, want := p.Details().Image(), (ociimage.Reference{
		Registry: "mm-1:5001", Name: "linux-ci", Tag: "latest",
	}); got != want {
		t.Errorf("Details().Image(): got %+v, want %+v", got, want)
	}
}

// TestTartConfigInvalidImage covers an image that is not a reference at all,
// which is reported when the configuration is validated rather than when the
// first VM fails to be cloned, and refused by the backend either way.
func TestTartConfigInvalidImage(t *testing.T) {
	cfg := tartImage("ghcr.io//ubuntu")
	cfg.RunnerDir = "/runner"
	err := cfg.Validate()
	if !errors.Is(err, ociimage.ErrInvalidReference) {
		t.Errorf("Validate: got %v, want ErrInvalidReference", err)
	}
	if err == nil || !strings.Contains(err.Error(), "tart_config.image") {
		t.Errorf("the error does not locate the setting: %v", err)
	}
	// A backend is not built from it, rather than being built around an image
	// that cannot be cloned.
	p, err := newTartBackend("linux", cfg, slog.Default())
	if !errors.Is(err, ociimage.ErrInvalidReference) {
		t.Errorf("newTartBackend: got %v, want ErrInvalidReference", err)
	}
	if p != nil {
		t.Error("newTartBackend returned a backend alongside the error")
	}
}

// fakeTart puts a stub tart on PATH that records its invocations, so that a
// pull can be observed without a registry.
func fakeTart(t *testing.T, exitCode int) func() []string {
	t.Helper()
	dir := t.TempDir()
	calls := filepath.Join(dir, "calls")
	script := "#!/bin/sh\necho \"$@\" >> " + strconv.Quote(calls) + "\nexit " + strconv.Itoa(exitCode) + "\n"
	if err := os.WriteFile(filepath.Join(dir, "tart"), []byte(script), 0700); err != nil { //nolint:gosec // test stub must be executable
		t.Fatalf("writing tart stub: %v", err)
	}
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	return func() []string {
		buf, err := os.ReadFile(calls)
		if err != nil {
			return nil // never invoked
		}
		return strings.Split(strings.TrimSpace(string(buf)), "\n")
	}
}

// TestPullRemoteOnRun verifies that a VM creation pulls the image first when
// configured to, and that the full reference, not the bare name, is pulled.
func TestPullRemoteOnRun(t *testing.T) {
	invocations := fakeTart(t, 0)
	p := tartBackendFor(t, "linux", TartConfig{Source: ociimage.Source{
		Image:           "mm-1:5001/linux-ci:latest",
		PullRemoteOnRun: true,
	}})

	if _, err := p.New(context.Background()); err != nil {
		t.Fatalf("New: %v", err)
	}
	got := invocations()
	if len(got) != 1 {
		t.Fatalf("tart invocations: got %v, want exactly one", got)
	}
	if want := "pull mm-1:5001/linux-ci:latest"; got[0] != want {
		t.Errorf("tart args: got %q, want %q", got[0], want)
	}
}

// TestPullRemoteOnRunNotPulled covers the cases where nothing is pulled: the
// option is off, or the image is local and has no registry to pull from.
func TestPullRemoteOnRunNotPulled(t *testing.T) {
	for _, tc := range []struct {
		name string
		cfg  TartConfig
	}{
		{"option off", tartImage("mm-1:5001/linux-ci:latest")},
		{"local image", TartConfig{Source: ociimage.Source{Image: "linux-ci", PullRemoteOnRun: true}}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			invocations := fakeTart(t, 0)
			p := tartBackendFor(t, "linux", tc.cfg)
			if _, err := p.New(context.Background()); err != nil {
				t.Fatalf("New: %v", err)
			}
			if got := invocations(); got != nil {
				t.Errorf("tart invocations: got %v, want none", got)
			}
		})
	}
}

// TestPullRemoteOnRunFails verifies that a failed pull fails the creation,
// rather than silently falling back to a stale cached image.
func TestPullRemoteOnRunFails(t *testing.T) {
	fakeTart(t, 1)
	p := tartBackendFor(t, "linux", TartConfig{Source: ociimage.Source{
		Image:           "mm-1:5001/linux-ci:latest",
		PullRemoteOnRun: true,
	}})

	inst, err := p.New(context.Background())
	if err == nil {
		t.Fatal("New: got nil error, want the failed pull to be reported")
	}
	if inst != nil {
		t.Error("New returned an instance alongside the error")
	}
	if !strings.Contains(err.Error(), "pulling mm-1:5001/linux-ci:latest") {
		t.Errorf("error %q does not name the image being pulled", err)
	}
}
