// ghpr creates and maintains the descriptions of GitHub pull requests using
// an ai agent, and records them in the git history.
//
// It is built around this workflow: branch off the base branch, commit as
// often as you like locally, push the branch, and raise one pull request that
// is squash merged. The description of that pull request is the only account
// of the change that survives the squash, so ghpr generates it from the diff,
// keeps it current, and once the pull request is merged attaches it as a git
// note to the single commit it produced:
//
//	ghpr create-pr 'chore: update deps'   # on the feature branch
//	ghpr update-summary                   # after pushing more commits to it
//	git switch main
//	ghpr post-note --delete-branch my-feature
//
// The description is generated by claude or agy, which are run with the diff
// and without permission to use tools, so that they summarize the change they
// are given and nothing else.
package main

import (
	"context"
	"fmt"
	"os"
	"syscall"

	"cloudeng.io/cmdutil"
	"cloudeng.io/cmdutil/cmdyaml"
	"cloudeng.io/cmdutil/subcmd"
)

const cmdSpec = `name: ghpr
summary: create and maintain github pull request descriptions with an ai agent
commands:
  - name: create-pr
    summary: create a pull request for the current branch, with a description generated from its diff
    args:
      - "<title> - the title of the pull request, eg. 'chore: update deps'"
  - name: update-summary
    summary: regenerate the description of a pull request from what its branch now changes
    args:
      - "[<branch>|<number>] - the pull request to update; defaults to the current branch"
  - name: post-note
    summary: attach the description of a merged pull request to the commit it created on the base branch
    args:
      - "<branch> - the feature branch whose pull request was merged"
  - name: config
    summary: config related commands
    commands:
      - name: show
        summary: show the current configuration
      - name: describe
        summary: describe the configuration spec
`

// SummaryCommandFlags are flags for showing the command that would be run to generate the summary.
type SummaryCommandFlags struct {
	ShowSummaryCommand bool `subcmd:"show-summary-command,false,show the command that would be run to generate the summary"`
	ShowCommand        bool `subcmd:"show-command,false,show the command that would be run to generate the summary"`
}

// GlobalFlags are the flags common to every command.
type GlobalFlags struct {
	ConfigFile   string `subcmd:"config,,'path to YAML configuration file; if unset, config.yaml or ghpr.yaml is searched in standard locations'"`
	Engine       string `subcmd:"engine,claude,'agent used to generate descriptions: claude or agy'"`
	Model        string `subcmd:"model,,model for the agent to use; the agent's own default if unset"`
	Base         string `subcmd:"base,main,branch that pull requests are merged into"`
	MaxDiffLines int    `subcmd:"max-diff-lines,3000,summarize the diff stat instead of the diff once it is longer than this; 0 for no limit"`
	Yes          bool   `subcmd:"yes,false,answer yes to every confirmation"`
	DryRun       bool   `subcmd:"dry-run,false,report what would be changed without changing it"`
	SummaryCommandFlags
	Verbose bool `subcmd:"verbose,false,explain what is being done"`
}

var globalFlags GlobalFlags

// CreateFlags are the flags for create-pr.
type CreateFlags struct {
	Draft bool `subcmd:"draft,false,create the pull request as a draft"`
	Push  bool `subcmd:"push,true,push the branch to origin if it is not there yet"`
	SummaryCommandFlags
}

// PostNoteFlags are the flags for post-note.
type PostNoteFlags struct {
	PushNotes    bool `subcmd:"push-notes,true,push refs/notes/* to origin once the note is attached"`
	DeleteBranch bool `subcmd:"delete-branch,false,delete the feature branch if its content is what was merged"`
	DeleteRemote bool `subcmd:"delete-remote,false,delete the feature branch from origin too; requires --delete-branch"`
}

// UpdateFlags are the flags for update-summary.
type UpdateFlags struct {
	SummaryCommandFlags
}

func configPrehook(ctx context.Context) (context.Context, string, subcmd.PostHook, error) {
	id := "withConfigPrehook"
	postHook := func(ctx context.Context) (string, error) { return id, nil }
	fs := subcmd.GlobalFlagSetFromContext(ctx)
	if fs == nil {
		return ctx, id, postHook, fmt.Errorf("global flagset not in context")
	}

	configFile := globalFlags.ConfigFile
	explicitlySet := fs.IsExplicitlySet("config")

	var foundFile string
	if explicitlySet {
		foundFile = cmdyaml.LocateConfigFileInDir(configFile, "ghpr")
		if foundFile == "" {
			return ctx, id, postHook, fmt.Errorf("configuration file %q not found", configFile)
		}
	} else {
		if configFile != "" {
			foundFile = cmdyaml.LocateConfigFileInDir(configFile, "ghpr")
		}
		if foundFile == "" {
			foundFile = cmdyaml.LocateConfigFileInDir("config", "ghpr")
		}
		if foundFile == "" {
			foundFile = cmdyaml.LocateConfigFileInDir("ghpr", "ghpr")
		}
	}

	if foundFile == "" {
		cfg := Config{Prompt: defaultInstructions}
		ctx = ContextWithConfig(ctx, cfg)
		return ctx, id, postHook, nil
	}

	if globalFlags.Verbose {
		fmt.Fprintf(os.Stderr, "ghpr: using configuration file %v\n", foundFile)
	}

	var cfg Config
	if err := cmdyaml.ParseConfigFilesStrict(ctx, &cfg, foundFile); err != nil {
		return ctx, id, postHook, fmt.Errorf("failed to read configuration file %q: %w\nedit that file to correct it", foundFile, err)
	}
	if err := cfg.Validate(); err != nil {
		return ctx, id, postHook, fmt.Errorf("configuration file %q is invalid: %w\nedit that file to correct it", foundFile, err)
	}

	ctx = ContextWithConfig(ctx, cfg)
	ctx = ContextWithConfigFile(ctx, foundFile)
	return ctx, id, postHook, nil
}

func newApp(ctx context.Context) *App {
	run := Runner(execRunner{})
	logf := func(string, ...any) {}
	if globalFlags.Verbose {
		logf = func(format string, args ...any) {
			fmt.Fprintf(os.Stderr, "ghpr: "+format+"\n", args...)
		}
	}
	git, gh := NewGit(run), NewGH(run)
	// A retry pauses for seconds, so it says so rather than appearing to
	// hang. This goes to stderr: stdout carries what was asked for.
	gh.notify = func(format string, args ...any) {
		fmt.Fprintf(os.Stderr, "ghpr: "+format, args...)
	}
	if globalFlags.DryRun {
		announce := func(cmd string) { fmt.Printf("would run: %v\n", cmd) }
		git, gh = git.DryRun(announce), gh.DryRun(announce)
	}
	cfg, _ := ConfigFromContext(ctx)
	return &App{
		Git:  git,
		GH:   gh,
		Base: globalFlags.Base,
		Summarizer: &Summarizer{
			git:          git,
			run:          run,
			engine:       globalFlags.Engine,
			model:        globalFlags.Model,
			maxDiffLines: globalFlags.MaxDiffLines,
			prompt:       cfg.Prompt,
			prompts:      cfg.Prompts,
			log:          logf,
		},
		Stdout:             os.Stdout,
		Stdin:              os.Stdin,
		AssumeYes:          globalFlags.Yes,
		DryRun:             globalFlags.DryRun,
		ShowSummaryCommand: globalFlags.ShowSummaryCommand || globalFlags.ShowCommand,
	}
}

func createPR(ctx context.Context, flags any, args []string) error {
	if len(args) != 1 {
		return fmt.Errorf("create-pr takes the title of the pull request as its only argument")
	}
	cf := flags.(*CreateFlags)
	app := newApp(ctx)
	if cf.ShowSummaryCommand || cf.ShowCommand {
		app.ShowSummaryCommand = true
	}
	return app.CreatePR(ctx, args[0], cf.Draft, cf.Push)
}

func updateSummary(ctx context.Context, flags any, args []string) error {
	if len(args) > 1 {
		return fmt.Errorf("update-summary takes at most one branch or pull request number")
	}
	target := ""
	if len(args) == 1 {
		target = args[0]
	}
	uf := flags.(*UpdateFlags)
	app := newApp(ctx)
	if uf.ShowSummaryCommand || uf.ShowCommand {
		app.ShowSummaryCommand = true
	}
	return app.UpdateSummary(ctx, target)
}

func postNote(ctx context.Context, flags any, args []string) error {
	if len(args) != 1 {
		return fmt.Errorf("post-note takes the merged feature branch as its only argument")
	}
	pf := flags.(*PostNoteFlags)
	if pf.DeleteRemote && !pf.DeleteBranch {
		return fmt.Errorf("--delete-remote needs --delete-branch: it deletes the branch from origin as well, not instead")
	}
	return newApp(ctx).PostNote(ctx, args[0], pf.PushNotes, pf.DeleteBranch, pf.DeleteRemote)
}

func createCLI() *subcmd.CommandSetYAML {
	cmdSet := subcmd.MustFromYAML(cmdSpec)
	cmdSet.Set("create-pr").MustRunner(createPR, &CreateFlags{})
	cmdSet.Set("create-pr").MustSetPreHooks(configPrehook)
	cmdSet.Set("update-summary").MustRunner(updateSummary, &UpdateFlags{})
	cmdSet.Set("update-summary").MustSetPreHooks(configPrehook)
	cmdSet.Set("post-note").MustRunner(postNote, &PostNoteFlags{})
	cmdSet.Set("post-note").MustSetPreHooks(configPrehook)

	cfgCmd := ConfigCommand{}
	cmdSet.Set("config", "show").MustRunner(cfgCmd.Show, &struct{}{})
	cmdSet.Set("config", "describe").MustRunner(cfgCmd.Describe, &struct{}{})
	cmdSet.Set("config").MustSetPreHooks(configPrehook)
	return cmdSet
}

func main() {
	ctx, cancel := context.WithCancelCause(context.Background())
	cli := createCLI()
	cli.WithGlobalFlags(subcmd.NewFlagSet().MustRegisterFlagStruct(&globalFlags, nil, nil))

	cmdutil.HandleSignals(func() { cancel(cmdutil.ErrInterrupt) }, os.Interrupt, syscall.SIGTERM)
	if err := cli.Dispatch(ctx); err != nil {
		if cmdutil.IsCleanShutdown(err, false) {
			return
		}
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
}
